import assert from 'node:assert/strict';
import test from 'node:test';
import { resolve, join } from 'node:path';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { temporaryDirectory } from '../helpers.mjs';
import { launchWorkspace, createProject, openProject, saveCheckpoint } from '../electron-flow.mjs';

test('real Electron bridge captures actual files with packaged-compatible ESM, stale tokens and no engineering writes', { timeout: 90000 }, async t => {
  let application;
  const dir = temporaryDirectory(t, () => application?.close());
  application = await launchWorkspace(join(dir, 'profile'));
  const page = await application.firstWindow();
  await page.getByRole('heading', { name: 'Start with a project' }).waitFor();
  await createProject(page, 'Keep context'); await openProject(page, 'Keep context');
  await saveCheckpoint(page, 'Before preview', 'Keep Resume intact');
  const before = await page.evaluate(async () => {
    const list = await window.workspace.listProjects();
    return (await window.workspace.openProject({ projectId: list.value[0].id })).value;
  });
  const file = resolve('docs/design/examples/ptb-v0.2/complex/project.md');
  const bytes = readFileSync(file);
  await application.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, file);
  const first = await page.evaluate(() => window.workspace.chooseBlueprintPreview());
  assert.equal(first.ok, true, JSON.stringify(first));
  assert.equal(first.value.kind, 'snapshot');
  assert.equal(first.value.snapshot.documents.length, 4);
  assert.equal(first.value.snapshot.records.length, 37);
  assert.equal(first.value.snapshot.relationships.length, 82);
  assert.equal(first.value.snapshot.validation, 'valid');
  assert.deepEqual(readFileSync(file), bytes);
  await application.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }); });
  assert.deepEqual(await page.evaluate(() => window.workspace.chooseBlueprintPreview()), { ok: true, value: { kind: 'cancelled' } });
  const refreshed = await page.evaluate(id => window.workspace.refreshBlueprintPreview({ sessionId: id }), first.value.snapshot.sessionId);
  assert.equal(refreshed.ok, true);
  assert.notEqual(refreshed.value.snapshot.snapshotId, first.value.snapshot.snapshotId);
  const hostile = await page.evaluate(id => window.workspace.refreshBlueprintPreview({ sessionId: id, path: 'C:/Windows' }), first.value.snapshot.sessionId);
  assert.equal(hostile.error.code, 'VALIDATION');
  assert.deepEqual(await page.evaluate(() => window.workspace.cancelBlueprintPreview()), { ok: true, value: undefined });
  const expired = await page.evaluate(id => window.workspace.refreshBlueprintPreview({ sessionId: id }), first.value.snapshot.sessionId);
  assert.equal(expired.error.code, 'NOT_FOUND');
  const after = await page.evaluate(id => window.workspace.openProject({ projectId: id }), before.project.id);
  assert.deepEqual(after.value, before);
  await page.getByRole('region', { name: 'Resume Development', exact: true }).getByText('Keep Resume intact', { exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => [typeof window.require, typeof window.process]), ['undefined', 'undefined']);
});

test('real Electron partial-invalid/source-null diagnostics remain inspectable without selecting a fabricated document', { timeout: 90000 }, async t => {
  let application;
  const dir = temporaryDirectory(t, () => application?.close());
  const entry = join(dir, 'missing-project.md');
  writeFileSync(entry, '# Plain context\nNo entity inferred from this heading.\n');
  application = await launchWorkspace(join(dir, 'profile'));
  const page = await application.firstWindow(); await page.getByRole('heading', { name: 'Start with a project' }).waitFor();
  await application.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, entry);
  const response = await page.evaluate(() => window.workspace.chooseBlueprintPreview());
  assert.equal(response.ok, true);
  const snapshot = response.value.snapshot;
  assert.equal(snapshot.validation, 'invalid'); assert.equal(snapshot.projectKey, null);
  const diag = snapshot.diagnostics.find(d => d.code === 'PROJECT_MISSING');
  assert.equal(diag.source, null); assert.equal(snapshot.records.length, 0);
  assert.equal(snapshot.documents[0].text, '# Plain context\nNo entity inferred from this heading.\n');
  writeFileSync(entry, '```ptb\n{"ptb":"0.2","kind":"project","id":"proj.x","id":"proj.y","title":"Duplicate"}\n```');
  const invalid = await page.evaluate(id => window.workspace.refreshBlueprintPreview({ sessionId: id }), snapshot.sessionId);
  assert.equal(invalid.value.snapshot.counts.unparsed, 1);
  assert.equal(invalid.value.snapshot.records[0].state, 'invalid-record');
  assert.ok(invalid.value.snapshot.diagnostics.some(d => d.code === 'DUPLICATE_KEY' && d.relatedSources.length));
  await page.evaluate(() => window.workspace.cancelBlueprintPreview());
  assert.equal((await page.evaluate(() => window.workspace.listProjects())).value.length, 0);
});
