import assert from 'node:assert/strict';
import test from 'node:test';
import { DatabaseSync } from 'node:sqlite';
import { mkdirSync, readFileSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { temporaryDirectory } from '../helpers.mjs';
import { launchWorkspace, openProject } from '../electron-flow.mjs';

test('packaged v2 upgrade preserves legacy memory and independently edited workflow copies after restart', { timeout: 120000 }, async t => {
  let application;
  const directory = temporaryDirectory(t, () => application?.close());
  mkdirSync(join(directory, 'data'));
  const filename = join(directory, 'data', 'workspace.sqlite');
  const legacy = new DatabaseSync(filename, { enableForeignKeyConstraints: true });
  legacy.exec(readFileSync(resolve('src/main/data/migrations/001_initial.sql'), 'utf8'));
  legacy.exec(readFileSync(resolve('src/main/data/migrations/002_release_progress.sql'), 'utf8'));
  legacy.prepare('INSERT INTO projects VALUES (?, ?, ?)').run(1, 'Packaged workflows', '2026-01-01T00:00:00.000Z');
  legacy.prepare('INSERT INTO actions VALUES (?, ?, ?, ?, ?)').run(1, 1, 'Unchanged legacy work', '2026-01-02T00:00:00.000Z', '2026-01-03T00:00:00.000Z');
  legacy.prepare('INSERT INTO checkpoints VALUES (?, ?, ?, ?, ?)').run(1, 1, 'Existing project memory', 'Continue with reusable workflow copies', '2026-01-04T00:00:00.000Z');
  legacy.exec('PRAGMA user_version = 2');
  legacy.close();
  const executable = resolve(process.env.PROJECTS_TIMELINE_EXECUTABLE ?? 'out/ProjectsTimeline-win32-x64/ProjectsTimeline.exe');
  application = await launchWorkspace(directory, executable);
  let page = await application.firstWindow();
  await openProject(page, 'Packaged workflows');
  const saved = await page.evaluate(async () => {
    const api = window.workspace;
    const value = result => { if (!result.ok) throw new Error(result.error.message); return result.value; };
    const builtin = value(await api.getWorkflowLibrary())[0];
    const source = value(await api.duplicateWorkflowTemplate({ templateId: builtin.template.id, expectedVersion: builtin.template.version, name: 'Packaged reusable' }));
    let master = value(await api.getWorkflowLibrary()).find(item => item.template.id === source.id);
    const action = master.actions[0];
    const { id, templateId, stageId, position, ...definition } = action;
    value(await api.updateWorkflowAction({ templateId, expectedVersion: master.template.version, actionId: id, stageId, ...definition, definitionOfDone: 'Observable packaged acceptance result' }));
    master = value(await api.getWorkflowLibrary()).find(item => item.template.id === source.id);
    const a = value(await api.createRelease({ projectId: 1, name: 'Packaged A', templateId: source.id, templateVersion: master.template.version }));
    const b = value(await api.createRelease({ projectId: 1, name: 'Packaged B', templateId: source.id, templateVersion: master.template.version }));
    let project = value(await api.openProject({ projectId: 1 }));
    for (const work of project.actions.filter(row => row.releaseId === a.id && row.kind === 'work')) value(await api.completeAction({ projectId: 1, actionId: work.id }));
    const proof = value(await api.recordReleaseVerification({ projectId: 1, releaseId: a.id, artifactIdentity: 'workflow packaged candidate fixture', evidenceReference: 'isolated packaged workflow suite', summary: 'Explicit provenance record exercising the final packaged path.', outcome: 'passed' }));
    value(await api.confirmRelease({ projectId: 1, releaseId: a.id, verificationId: proof.id }));
    const frozen = value(await api.openProject({ projectId: 1 })).releases.find(item => item.release.id === a.id);
    value(await api.updateWorkflowTemplate({ templateId: source.id, expectedVersion: master.template.version, name: 'Improved master', description: 'Changed after application' }));
    master = value(await api.getWorkflowLibrary()).find(item => item.template.id === source.id);
    value(await api.removeWorkflowAction({ templateId: source.id, expectedVersion: master.template.version, actionId: action.id }));
    project = value(await api.openProject({ projectId: 1 }));
    const local = project.actions.find(row => row.releaseId === b.id && row.kind === 'work');
    const { position: localPosition, ...localDetails } = local.details;
    value(await api.updateReleaseAction({ projectId: 1, actionId: local.id, title: 'Release-local packaged definition', ...localDetails, instructions: 'Local definition stays independent of master edits.' }));
    value(await api.addReleaseStage({ projectId: 1, releaseId: b.id, name: 'Release-local review' }));
    return { project: value(await api.openProject({ projectId: 1 })), library: value(await api.getWorkflowLibrary()), frozen, aId: a.id, bId: b.id };
  });
  assert.deepEqual(saved.project.releases.find(item => item.release.id === saved.aId), saved.frozen);
  assert.equal(saved.frozen.progress.percent, 100);
  assert.equal(saved.frozen.stages.length, 7);
  assert.equal(saved.project.releases.find(item => item.release.id === saved.bId).progress.percent, null);
  assert.equal(saved.project.actions.find(action => action.id === 1).details, null);
  assert.equal(saved.project.actions.find(action => action.id === 1).completedAt, '2026-01-03T00:00:00.000Z');
  assert.equal(saved.frozen.release.sourceTemplateName, 'Packaged reusable');
  assert.equal(saved.frozen.release.sourceTemplateVersion, 2);
  assert.equal(saved.library.find(item => item.template.name === 'Improved master').template.version, 4);
  assert.equal(readdirSync(join(directory, 'data')).filter(file => file.includes('.before-v4.') && file.endsWith('.bak')).length, 1);
  await application.close();
  application = await launchWorkspace(directory, executable);
  page = await application.firstWindow();
  await openProject(page, 'Packaged workflows');
  const recovered = await page.evaluate(async () => ({ project: (await window.workspace.openProject({ projectId: 1 })).value, library: (await window.workspace.getWorkflowLibrary()).value }));
  assert.deepEqual(recovered.project, saved.project);
  assert.deepEqual(recovered.library, saved.library);
  await page.getByRole('region', { name: 'Resume Development', exact: true }).getByText('Continue with reusable workflow copies', { exact: true }).waitFor();
  const raw = new DatabaseSync(filename);
  try { assert.equal(raw.prepare('PRAGMA user_version').get().user_version, 4); assert.deepEqual(raw.prepare('PRAGMA foreign_key_check').all(), []); }
  finally { raw.close(); }
});
